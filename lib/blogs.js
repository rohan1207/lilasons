export function getBlog(slug) {
  return BLOGS.find((b) => b.slug === slug) || null;
}

export function getAdjacentBlogs(slug) {
  const index = BLOGS.findIndex((b) => b.slug === slug);
  if (index < 0) return { prev: null, next: null };
  return {
    prev: index > 0 ? BLOGS[index - 1] : null,
    next: index < BLOGS.length - 1 ? BLOGS[index + 1] : null,
  };
}

export function getRelatedBlogs(slug, limit = 3) {
  const current = getBlog(slug);
  if (!current) return [];
  const same = BLOGS.filter(
    (b) => b.slug !== slug && b.category === current.category,
  );
  const filler = BLOGS.filter(
    (b) => b.slug !== slug && b.category !== current.category,
  );
  return [...same, ...filler].slice(0, limit);
}
